package org.apache.commons.csv;

import static org.junit.jupiter.api.Assertions.fail;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

/**
 * Approved Scenarios runner.
 *
 * <p>
 * Each fixture under {@code src/test/resources/approved} is a Markdown file split by a marker line. Everything above the marker is authored by a human (title,
 * rationale, input CSV, parser configuration). Everything below the marker is regenerated by this runner from an actual parse, and compared against what is on
 * disk. Reviewing a new test case therefore means reading a Markdown diff, never assertion code.
 * </p>
 *
 * <p>
 * The execution logic below is validated once. After that, adding a case is adding a fixture.
 * </p>
 */
public class ApprovedScenariosTest {

    private static final Path APPROVED_DIR = Paths.get("src", "test", "resources", "approved");

    /** Everything from this line on is machine-generated. Human-authored facts live above it. */
    private static final String MARKER = "<!-- 以下由 runner 生成，请勿手工编辑 -->";

    private static final String APPROVE_ENV = "APPROVE";

    static List<Path> scenarios() throws IOException {
        final List<Path> files = new ArrayList<>();
        try (DirectoryStream<Path> stream = Files.newDirectoryStream(APPROVED_DIR, "*.approved.md")) {
            for (final Path path : stream) {
                files.add(path);
            }
        }
        Collections.sort(files);
        return files;
    }

    private static String fencedBlockAfter(final String text, final String heading) {
        final int headingAt = text.indexOf(heading);
        if (headingAt < 0) {
            throw new IllegalArgumentException("Fixture is missing the section: " + heading);
        }
        final int openAt = text.indexOf("```", headingAt);
        if (openAt < 0) {
            throw new IllegalArgumentException("Section has no fenced block: " + heading);
        }
        final int openLineEnd = text.indexOf('\n', openAt);
        final int closeAt = text.indexOf("```", openLineEnd);
        if (closeAt < 0) {
            throw new IllegalArgumentException("Fenced block is never closed in section: " + heading);
        }
        return text.substring(openLineEnd + 1, closeAt);
    }

    private static Map<String, String> parseConfig(final String block) {
        final Map<String, String> config = new LinkedHashMap<>();
        for (final String rawLine : block.split("\n")) {
            final String line = rawLine.trim();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            final int equalsAt = line.indexOf('=');
            if (equalsAt < 0) {
                throw new IllegalArgumentException("Configuration line is not key = value: " + line);
            }
            config.put(line.substring(0, equalsAt).trim(), line.substring(equalsAt + 1).trim());
        }
        return config;
    }

    private static String[] splitList(final String value) {
        if (value == null || value.trim().isEmpty()) {
            return new String[0];
        }
        final String[] parts = value.split(",");
        for (int i = 0; i < parts.length; i++) {
            parts[i] = parts[i].trim();
        }
        return parts;
    }

    private static CSVFormat buildFormat(final Map<String, String> config) {
        final String base = config.getOrDefault("format", "DEFAULT");
        final CSVFormat seed;
        if ("DEFAULT".equals(base)) {
            seed = CSVFormat.DEFAULT;
        } else if ("RFC4180".equals(base)) {
            seed = CSVFormat.RFC4180;
        } else if ("EXCEL".equals(base)) {
            seed = CSVFormat.EXCEL;
        } else {
            throw new IllegalArgumentException("Unsupported format: " + base);
        }
        final CSVFormat.Builder builder = seed.builder();
        final String header = config.get("header");
        if (header != null && !header.trim().isEmpty()) {
            if ("FROM_FIRST_RECORD".equals(header.trim())) {
                builder.setHeader();
            } else {
                builder.setHeader(splitList(header)).setSkipHeaderRecord(true);
            }
        }
        final String required = config.get("requiredHeaders");
        if (required != null && !required.trim().isEmpty()) {
            builder.setRequiredHeaders(splitList(required));
        }
        return builder.get();
    }

    private static String render(final String head) {
        final String input = fencedBlockAfter(head, "## 输入");
        final Map<String, String> config = parseConfig(fencedBlockAfter(head, "## 配置"));
        final StringBuilder out = new StringBuilder();
        try {
            final CSVFormat format = buildFormat(config);
            final List<String> headerNames;
            final List<String> recordLines = new ArrayList<>();
            try (CSVParser parser = CSVParser.parse(input, format)) {
                headerNames = parser.getHeaderNames();
                int index = 0;
                for (final CSVRecord record : parser) {
                    index++;
                    final StringBuilder line = new StringBuilder();
                    line.append(index).append(": ");
                    for (int i = 0; i < record.size(); i++) {
                        if (i > 0) {
                            line.append(" | ");
                        }
                        final String name = i < headerNames.size() ? headerNames.get(i) : "#" + i;
                        line.append('[').append(name).append("]=").append(record.get(i));
                    }
                    recordLines.add(line.toString());
                }
            }
            out.append("## 表头\n\n```text\n");
            if (headerNames.isEmpty()) {
                out.append("(无表头)\n");
            } else {
                final StringBuilder names = new StringBuilder();
                for (final String name : headerNames) {
                    if (names.length() > 0) {
                        names.append(" | ");
                    }
                    names.append('[').append(name).append(']');
                }
                out.append(names).append('\n');
            }
            out.append("```\n\n## 记录\n\n```text\n");
            if (recordLines.isEmpty()) {
                out.append("(无记录)\n");
            } else {
                for (final String line : recordLines) {
                    out.append(line).append('\n');
                }
            }
            out.append("```\n");
        } catch (final Exception e) {
            out.append("## 异常\n\n```text\n");
            out.append(e.getClass().getSimpleName()).append(": ").append(e.getMessage()).append('\n');
            out.append("```\n");
        }
        return out.toString();
    }

    private static String normalize(final String text) {
        final String[] lines = text.replace("\r\n", "\n").replace('\r', '\n').split("\n", -1);
        final StringBuilder sb = new StringBuilder();
        for (final String line : lines) {
            int end = line.length();
            while (end > 0 && (line.charAt(end - 1) == ' ' || line.charAt(end - 1) == '\t')) {
                end--;
            }
            sb.append(line, 0, end).append('\n');
        }
        String result = sb.toString();
        while (result.endsWith("\n\n")) {
            result = result.substring(0, result.length() - 1);
        }
        return result;
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("scenarios")
    public void scenario(final Path fixture) throws IOException {
        final String text = new String(Files.readAllBytes(fixture), StandardCharsets.UTF_8);
        final int markerAt = text.indexOf(MARKER);
        if (markerAt < 0) {
            fail("Fixture has no generation marker line: " + fixture);
        }
        final String head = text.substring(0, markerAt);
        final String approved = text.substring(markerAt);
        final String actual = MARKER + "\n\n" + render(head);

        final Path received = Paths.get(fixture.toString().replace(".approved.md", ".received.md"));
        if (normalize(approved).equals(normalize(actual))) {
            Files.deleteIfExists(received);
            return;
        }
        final String rebuilt = head + actual;
        if ("1".equals(System.getenv(APPROVE_ENV))) {
            Files.write(fixture, rebuilt.getBytes(StandardCharsets.UTF_8));
            Files.deleteIfExists(received);
            return;
        }
        Files.write(received, rebuilt.getBytes(StandardCharsets.UTF_8));
        fail(String.join("\n", Arrays.asList(
                "Scenario differs from the approved facts: " + fixture.getFileName(),
                "Review the Markdown diff: " + received,
                "",
                "--- approved ---",
                normalize(approved),
                "--- actual ---",
                normalize(actual))));
    }
}
